function unsplash(photoId: string, w = 2560, q = 82): string {
  return `https://images.unsplash.com/${photoId}?auto=format&fit=crop&w=${w}&q=${q}`;
}

function thumb(photoId: string): string {
  return `https://images.unsplash.com/${photoId}?auto=format&fit=crop&w=640&q=75`;
}

